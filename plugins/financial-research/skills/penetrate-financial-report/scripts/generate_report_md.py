"""
穿透财报分析报告生成器 —— Markdown 版

生成与 DOCX 版结构、科目、四要素分析、财务指标维度一致的 Markdown 报告，
仅将呈现形式适配为 Markdown 以提升阅读体验：
- 用 # / ## / ### 标题层级替代 Word 的 Title/Heading1/Heading2
- 用 Markdown 表格（| ... |）替代 Word 表格
- 变动>20% 的科目用 **加粗** + 🔴 标记（替代 Word 的标红，Markdown 无原生字体色）
- 重要提示/免责声明用 > 引用块 + **加粗** 强调
- 采用经用户反馈验证效果最佳的纯文字 + Markdown 表格形态，不生成或嵌入图片

数据颗粒度、完整性、涉及的财务指标维度与 DOCX 版一致：
- 资产负债表约 67 科目、三时点、净增额+增长率
- 利润表约 28 科目、本年vs上年净增额+增长率、最新Q1单季度同比
- 每个科目变动配套四要素深度分析（≥150字/条）
本脚本仅负责搭建带占位符（___、{上年}、{本年}、{最新Q1} 等）的报告骨架，
执行时须根据一手数据（公告 / 路演纪要）逐项填充。

用法:
    python generate_report_md.py --company "宁德时代" [--output report.md]

无第三方依赖（纯标准库）。
"""

import argparse
import re
from datetime import datetime


FORBIDDEN_VISUAL_PATTERN = re.compile(
    r"!\[[^\]]*\]\([^)]+\)|<img\b|<svg\b|```mermaid\b", re.IGNORECASE
)


def ensure_text_only(markdown):
    """确保报告保持纯文字与 Markdown 表格形态。"""
    if FORBIDDEN_VISUAL_PATTERN.search(markdown):
        raise ValueError("报告仅允许文字与 Markdown 表格，禁止包含图片或图形化内容")


# ============================================================
# Markdown 渲染辅助
# ============================================================


def md_table(headers, rows):
    """把表头与数据行渲染为 Markdown 表格字符串。
    对含「合计/总计/合计数」等汇总行加粗，提升可读性。
    """

    def esc(x):
        # 转义竖线，避免破坏 Markdown 表格结构
        return str(x).replace("|", "\\|").replace("\n", " ")

    lines = []
    lines.append("| " + " | ".join(esc(h) for h in headers) + " |")
    lines.append("| " + " | ".join(["---"] * len(headers)) + " |")
    for row in rows:
        cells = [esc(c) for c in row]
        # 合计/总计行整行加粗
        first = str(row[0]) if row else ""
        if any(k in first for k in ["合计", "总计"]):
            cells = ["**" + c + "**" if c else c for c in cells]
        lines.append("| " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


class MD:
    """Markdown 文档累加器，接口对齐 DOCX 版的 add_* 函数以保证内容一致。"""

    def __init__(self):
        self.buf = []

    # --- 标题 ---
    def heading(self, text, level=1):
        # level 0=报告标题(#) 1=第X部分(##) 2=X.Y(###) 3=(####)
        hashes = "#" * (level + 1)
        self.buf.append("\n" + hashes + " " + text + "\n")

    # --- 普通正文段落 ---
    def para(self, text, bold=False):
        t = ("**" + text + "**") if bold else text
        self.buf.append("\n" + t + "\n")

    # --- 注释/辅助小字（Markdown 用斜体 + 引用弱化） ---
    def note(self, text):
        self.buf.append("\n> *" + text + "*\n")

    # --- 醒目提示块（对齐 DOCX 的红色加粗警示） ---
    def warn(self, text):
        self.buf.append("\n> ⚠️ **" + text + "**\n")

    # --- 正文（长段落自然成段，Markdown 无需按 200 字硬拆） ---
    def body(self, text):
        self.buf.append("\n" + text + "\n")

    # --- 论证条目（四要素分析，保留编号符号 ①②③…） ---
    def argument(self, text):
        self.buf.append("\n" + text + "\n")

    # --- 表格 ---
    def table(self, headers, rows):
        self.buf.append("\n" + md_table(headers, rows))

    # --- 列表项 ---
    def bullet(self, text):
        self.buf.append(text)

    # --- 水平分隔线（替代 DOCX 分页符，Markdown 用 --- 分节） ---
    def hr(self):
        self.buf.append("\n---\n")

    def render(self):
        # 合并并压缩多余空行
        text = "\n".join(self.buf)
        text = re.sub(r"\n{3,}", "\n\n", text)
        return text.strip() + "\n"


